def data_jerar(punto):
    """Jerarquía temporal: da más peso a los últimos 8 datos."""
    punto = list(punto)
    ultimos = punto[-8:]
    resultado = []
    for i, valor in enumerate(ultimos):
        peso = i + 1
        resultado.extend([valor] * peso)
    return resultado


def safe_mode(data_list, default_value="UNKNOWN"):
    """Mode seguro que no lanza excepción."""
    if not data_list:
        return default_value
    try:
        return std.mode(data_list)
    except std.StatisticsError:
        return default_value
    except Exception:
        return default_value


def get_tba_score_for_team(team_id, match_num, matches_df):
    """
    Retorna (auto_score, tele_score, endgame_score) de TBA para un equipo en un match específico.
    Busca si el equipo estaba en alianza AZUL o ROJA y devuelve los scores correspondientes.
    Si no encuentra el match o el equipo, retorna (0, 0, 0).
    """
    match_num_str = str(match_num)
    fila = matches_df[matches_df['match_num'].astype(str) == match_num_str]
    if fila.empty:
        return 0, 0, 0

    row = fila.iloc[0]
    azul = [row["AZUL1"], row["AZUL2"], row["AZUL3"]]
    rojo = [row["ROJO1"], row["ROJO2"], row["ROJO3"]]

    if team_id in azul:
        # Dividir entre 3 porque el score es de toda la alianza
        auto_s     = row.get("blue_auto_score", 0) / 3
        tele_s     = row.get("blue_tele_score", 0) / 3
        endgame_s  = row.get("blue_endgame_score", 0) / 3
    elif team_id in rojo:
        auto_s     = row.get("red_auto_score", 0) / 3
        tele_s     = row.get("red_tele_score", 0) / 3
        endgame_s  = row.get("red_endgame_score", 0) / 3
    else:
        return 0, 0, 0

    return auto_s, tele_s, endgame_s


