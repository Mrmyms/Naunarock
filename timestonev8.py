def matches_in_reg_tba(reg, season):
    """GET matches list from TBA.
    reg: String regional code as 'okok'
    season: integer year of the season
    returns list of match objects
    """
    variable_url = 'event/' + str(season) + reg.lower() + '/matches'
    url = base_url_tba + variable_url
    response = requests.get(url, headers=headers)
    matches = json.loads(response.text)
    return matches


def clean_match_results(matches):
    """Clean match results from TBA 2026.
    matches: list of match objects
    returns DataFrame with clean match results including breakdown scores from TBA
    """
    clean_matches = []
    for match in matches:
        try:
            score_breakdown = match.get("score_breakdown")
            if score_breakdown is None:
                print(f"Skipping match {match.get('key', 'unknown')} - missing score_breakdown.")
                continue

            blue_alliance  = match.get("alliances", {}).get("blue", {})
            red_alliance   = match.get("alliances", {}).get("red", {})
            blue_breakdown = score_breakdown.get("blue", {})
            red_breakdown  = score_breakdown.get("red", {})

            # ----- Auto scores por alianza desde TBA -----
            # TBA 2026: autoPoints contiene los puntos de autonomo
            blue_auto  = blue_breakdown.get("autoPoints", 0)
            red_auto   = red_breakdown.get("autoPoints", 0)

            # ----- Tele scores por alianza desde TBA -----
            # teleopPoints = total - auto - endgame - foulPoints
            blue_tele = blue_breakdown.get("teleopPoints", 0)
            red_tele  = red_breakdown.get("teleopPoints", 0)

            # ----- Endgame por alianza desde TBA -----
            blue_endgame = blue_breakdown.get("endGamePoints", 0)
            red_endgame  = red_breakdown.get("endGamePoints", 0)

            clean_match = {
                "match_code":        match["key"],
                # Equipos
                "blue_1": blue_alliance.get("team_keys", ["", "", ""])[0].replace("frc", ""),
                "blue_2": blue_alliance.get("team_keys", ["", "", ""])[1].replace("frc", ""),
                "blue_3": blue_alliance.get("team_keys", ["", "", ""])[2].replace("frc", ""),
                "red_1":  red_alliance.get("team_keys",  ["", "", ""])[0].replace("frc", ""),
                "red_2":  red_alliance.get("team_keys",  ["", "", ""])[1].replace("frc", ""),
                "red_3":  red_alliance.get("team_keys",  ["", "", ""])[2].replace("frc", ""),
                # Puntajes totales
                "blue_total_score":  blue_alliance.get("score", 0),
                "red_total_score":   red_alliance.get("score", 0),
                # Puntajes por fase desde TBA
                "blue_auto_score":   blue_auto,
                "red_auto_score":    red_auto,
                "blue_tele_score":   blue_tele,
                "red_tele_score":    red_tele,
                "blue_endgame_score": blue_endgame,
                "red_endgame_score":  red_endgame,
            }
            clean_matches.append(clean_match)
        except KeyError as e:
            print(f"Skipping match {match.get('key', 'unknown')} - missing key: {e}")
            continue
    return clean_matches


