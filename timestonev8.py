def simular_match(match_num):
    """
    Simula un match completo (2 alianzas, 6 robots).
    match_num: número del match (1-based)
    """
    # Buscar el match por match_num en vez de usar iloc directamente
    fila_match = matches[matches['match_num'] == match_num]
    if fila_match.empty:
        print(f"Match {match_num} no encontrado.")
        return {}, {}

    current_match = fila_match.iloc[0]

    rojo1 = int(current_match.get("ROJO1", 0))
    rojo2 = int(current_match.get("ROJO2", 0))
    rojo3 = int(current_match.get("ROJO3", 0))
    azul1 = int(current_match.get("AZUL1", 0))
    azul2 = int(current_match.get("AZUL2", 0))
    azul3 = int(current_match.get("AZUL3", 0))

    # Simular alianzas (cada robot se simula una sola vez por alianza)
    puntaje_rojo, rob_r1, rob_r2, rob_r3 = simular_alianza(rojo1, rojo2, rojo3, 1)
    puntaje_azul, rob_a1, rob_a2, rob_a3 = simular_alianza(azul1, azul2, azul3, 0)

    alianzas = {"ROJO": puntaje_rojo, "AZUL": puntaje_azul}
    robots   = {
        "rojo1": rob_r1, "rojo2": rob_r2, "rojo3": rob_r3,
        "azul1": rob_a1, "azul2": rob_a2, "azul3": rob_a3
    }

    # Patrón de luces: gana el auto mayor
    auto_rojo = rob_r1.get("auto_min", 0) + rob_r2.get("auto_min", 0) + rob_r3.get("auto_min", 0)
    auto_azul = rob_a1.get("auto_min", 0) + rob_a2.get("auto_min", 0) + rob_a3.get("auto_min", 0)
    alianzas["patron_luces"] = patron_luces.get("azul" if auto_azul >= auto_rojo else "rojo", "UNKNOWN")

    return alianzas, robots

