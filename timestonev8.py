# Usa los puntajes de TBA (auto, tele, endgame) en lugar de los totales del scouting.
# El scouting se usa únicamente para datos cualitativos:
#   POS INICIAL, AUTO MOVE, AUTO NVL1, GLOTON, CRUZA MEDIA CANCHA, ENDGAME, SHOOTER, HUMAN

def simular_robot(equipo, datos, equipos, matches_sched):
    """
    Simula un robot usando datos cualitativos de scouting y puntajes cuantitativos de TBA.

    Args:
        equipo: Team ID (int)
        datos: DataFrame con datos de scouting
        equipos: DataFrame con info de equipos (Team ID, Names)
        matches_sched: DataFrame con schedule (no usado para scores, sólo referencia)

    Returns:
        dict con todas las métricas del robot
    """
    robot = {
        "equipo":             int(equipo),
        "nombre":             "nombre",
        "jugados":            0,
        "posicion_A":         "UNKNOWN",
        "posicion_B":         "UNKNOWN",
        "posicion_C":         "UNKNOWN",
        "auto_media_cancha":  "UNKNOWN",
        "gloton":             "UNKNOWN",
        "auto_move":          "UNKNOWN",
        "auto_nvl1_est":      "UNKNOWN",
        # Scores de TBA (promedios por partido)
        "auto_prom":          0.0,
        "auto_desv":          0.0,
        "auto_var":           0.0,
        "tele_prom":          0.0,
        "tele_desv":          0.0,
        "tele_var":           0.0,
        "endgame_nvl3_prob":  0,
        "endgame_nvl2_prob":  0,
        "endgame_nvl1_prob":  0,
        "endgame_none_prob":  0,
        "tipo_endgame":       "NONE",
        "endgame_score_est":  0,
        "endgame_score_min":  0,
        "endgame_score_max":  0,
        # Estimados finales
        "auto_est":           0,
        "auto_min":           0,
        "auto_max":           0,
        "tele_est":           0,
        "tele_min":           0,
        "tele_max":           0,
        "score_est":          0,
        "score_min":          0,
        "score_max":          0,
        "human":              0,
        "EPA":                0
    }

    try:
        # --- Datos de scouting para este equipo ---
        data = datos.loc[datos["EQUIPO"] == equipo].reset_index(drop=True).fillna(0)

        nombre_vals = equipos.loc[equipos["Team ID"] == equipo, "Names"].values
        robot["nombre"] = nombre_vals[0] if len(nombre_vals) > 0 else "Sin nombre"

        if len(data) == 0:
            return robot

        robot["jugados"] = len(data)

        # --- Datos cualitativos de scouting ---
        pos = list(data["POS INICIAL"]) if "POS INICIAL" in data.columns else []
        robot["posicion_A"] = pos.count("A")
        robot["posicion_B"] = pos.count("B")
        robot["posicion_C"] = pos.count("C")

        if "GLOTON" in data.columns:
            robot["gloton"] = safe_mode(data_jerar(data["GLOTON"]), "UNKNOWN")

        if "CRUZA MEDIA CANCHA" in data.columns:
            robot["auto_media_cancha"] = safe_mode(data_jerar(data["CRUZA MEDIA CANCHA"]), "UNKNOWN")

        if "AUTO MOVE" in data.columns:
            robot["auto_move"] = safe_mode(data_jerar(data["AUTO MOVE"]), "UNKNOWN")

        if "AUTO NVL1" in data.columns:
            robot["auto_nvl1_est"] = safe_mode(data_jerar(data["AUTO NVL1"]), "UNKNOWN")

        # --- Scores cuantitativos desde TBA ---
        # Para cada match del scouting, sacamos los scores reales de TBA
        auto_scores_tba    = []
        tele_scores_tba    = []

        for i in range(len(data)):
            match_num = data["MATCH"].iloc[i]  # ya es string limpio
            auto_s, tele_s, endgame_s = get_tba_score_for_team(equipo, match_num, matches)
            if auto_s == 0 and tele_s == 0 and endgame_s == 0:
                # Match no encontrado en TBA (quizás aún no jugado)
                continue
            auto_scores_tba.append(auto_s)
            tele_scores_tba.append(tele_s)

        # --- AUTO (desde TBA) ---
        if auto_scores_tba:
            arr_auto = np.array(auto_scores_tba)
            robot["auto_prom"] = round(np.mean(arr_auto), 2)
            robot["auto_desv"] = round(np.std(arr_auto), 2)
            robot["auto_var"]  = round(np.var(arr_auto), 2)

        # --- TELE (desde TBA) ---
        if tele_scores_tba:
            arr_tele = np.array(tele_scores_tba)
            # Filtrar outliers con IQR
            q25 = np.quantile(arr_tele, 0.25)
            q75 = np.quantile(arr_tele, 0.75)
            filtrado = arr_tele[(arr_tele >= q25) & (arr_tele <= q75)]
            if filtrado.size > 0:
                robot["tele_prom"] = round(np.mean(filtrado), 2)
                robot["tele_desv"] = round(np.std(filtrado), 2)
                robot["tele_var"]  = round(np.var(filtrado), 2)
            else:
                robot["tele_prom"] = round(np.mean(arr_tele), 2)
                robot["tele_desv"] = round(np.std(arr_tele), 2)
                robot["tele_var"]  = round(np.var(arr_tele), 2)

        # --- ENDGAME (cualitativo de scouting) ---
        if "ENDGAME" in data.columns and not data["ENDGAME"].empty:
            jerar_endgame = list(data_jerar(data["ENDGAME"]))
            if jerar_endgame:
                n = len(jerar_endgame)
                robot["endgame_nvl3_prob"] = round(jerar_endgame.count('NVL3') / n * 100)
                robot["endgame_nvl2_prob"] = round(jerar_endgame.count('NVL2') / n * 100)
                robot["endgame_nvl1_prob"] = round(jerar_endgame.count('NVL1') / n * 100)
                robot["endgame_none_prob"] = round(jerar_endgame.count('NONE') / n * 100)

                robot["tipo_endgame"]     = safe_mode(jerar_endgame, "NONE")
                robot["endgame_score_est"] = scores.get(robot["tipo_endgame"], 0)

                # Endgame MÍNIMO: el peor nivel que ocurre ≥ 1% del tiempo
                robot["endgame_score_min"] = scores.get("NVL3", 0)  # inicia en mejor
                if robot["endgame_nvl1_prob"] >= 1:
                    robot["endgame_score_min"] = scores.get("NVL1", 0)
                if robot["endgame_none_prob"] >= 1:
                    robot["endgame_score_min"] = scores.get("NONE", 0)

                # Endgame MÁXIMO: el mejor nivel que ocurre ≥ 1% del tiempo
                robot["endgame_score_max"] = scores.get("NONE", 0)  # inicia en peor
                if robot["endgame_nvl1_prob"] >= 1:
                    robot["endgame_score_max"] = scores.get("NVL1", 0)
                if robot["endgame_nvl2_prob"] >= 1:
                    robot["endgame_score_max"] = scores.get("NVL2", 0)
                if robot["endgame_nvl3_prob"] >= 1:
                    robot["endgame_score_max"] = scores.get("NVL3", 0)

        # --- HUMAN (cualitativo de scouting) ---
        if "HUMAN" in datos.columns and not datos["HUMAN"].empty:
            robot["human"] = round(np.nan_to_num(np.mean(datos["HUMAN"])))

        # --- Estimados finales ---
        robot["auto_est"] = robot["auto_prom"]
        robot["auto_min"] = max(0, robot["auto_prom"] - robot["auto_desv"])
        robot["auto_max"] = robot["auto_prom"] + robot["auto_desv"]

        robot["tele_est"] = robot["tele_prom"]
        robot["tele_min"] = max(0, robot["tele_prom"] - robot["tele_desv"])
        robot["tele_max"] = robot["tele_prom"] + robot["tele_desv"]

        robot["score_est"] = robot["auto_est"] + robot["tele_est"] + robot["endgame_score_est"]
        robot["score_min"] = robot["auto_min"] + robot["tele_min"] + robot["endgame_score_min"]
        robot["score_max"] = robot["auto_max"] + robot["tele_max"] + robot["endgame_score_max"]

        # EPA: ponderación de auto (35%), tele (45%), endgame (40%)
        robot["EPA"] = max(0, int(
            0.35 * robot["auto_est"] +
            0.45 * robot["tele_est"] +
            0.40 * robot["endgame_score_est"]
        ))

    except Exception as e:
        print(f"Error inesperado para equipo {equipo}: {e}")

    return robot

