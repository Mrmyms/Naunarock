def write_to_gss(gss, sheet, data):
    """(RE)WRITE content to a GSS.
    gss: Spreadsheet object
    sheet: string target sheet name
    data: DataFrame to write
    """
    try:
        data_sheet = gss.worksheet(sheet)
        data_sheet.clear()
    except gspread.exceptions.WorksheetNotFound:
        data_sheet = gss.add_worksheet(title=sheet, rows="1", cols="1")
    data_sheet.update([data.columns.values.tolist()] + data.values.tolist())


