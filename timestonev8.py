def simular_alianza(r1, r2, r3, color):
    """
    Simula una alianza completa (3 robots).
    color: 0 = AZUL, 1 = ROJO
    """
    rob1 = simular_robot(r1, datos, teams_df, matches_schedule)
    rob2 = simular_robot(r2, datos, teams_df, matches_schedule)
    rob3 = simular_robot(r3, datos, teams_df, matches_schedule)

    alianza_color = "AZUL" if color == 0 else "ROJO"

    # Desviación de la alianza = sqrt(suma de varianzas)
    auto_desv_alianza = round(np.sqrt(
        rob1.get("auto_var", 0) + rob2.get("auto_var", 0) + rob3.get("auto_var", 0)
    ))
    tele_desv_alianza = round(np.sqrt(
        rob1.get("tele_var", 0) + rob2.get("tele_var", 0) + rob3.get("tele_var", 0)
    ))

    puntaje = {
        "color":                alianza_color,
        "auto_desv_alianza":    auto_desv_alianza,
        "tele_desv_alianza":    tele_desv_alianza,
    }

    # AUTO
    puntaje["auto_est"]  = rob1.get("auto_prom", 0) + rob2.get("auto_prom", 0) + rob3.get("auto_prom", 0)
    puntaje["auto_min"]  = max(0, puntaje["auto_est"] - auto_desv_alianza)
    puntaje["auto_max"]  = puntaje["auto_est"] + auto_desv_alianza

    # TELE
    puntaje["tele_est"]  = rob1.get("tele_prom", 0) + rob2.get("tele_prom", 0) + rob3.get("tele_prom", 0)
    puntaje["tele_min"]  = max(0, puntaje["tele_est"] - tele_desv_alianza)
    puntaje["tele_max"]  = puntaje["tele_est"] + tele_desv_alianza

    # ENDGAME
    puntaje["endgame_score_est"] = rob1.get("endgame_score_est", 0) + rob2.get("endgame_score_est", 0) + rob3.get("endgame_score_est", 0)
    puntaje["endgame_score_min"] = rob1.get("endgame_score_min", 0) + rob2.get("endgame_score_min", 0) + rob3.get("endgame_score_min", 0)
    puntaje["endgame_score_max"] = rob1.get("endgame_score_max", 0) + rob2.get("endgame_score_max", 0) + rob3.get("endgame_score_max", 0)

    puntaje["tipo_endgame_1"] = rob1.get("tipo_endgame", "NONE")
    puntaje["tipo_endgame_2"] = rob2.get("tipo_endgame", "NONE")
    puntaje["tipo_endgame_3"] = rob3.get("tipo_endgame", "NONE")

    # TOTALES
    puntaje["score_est_total"] = puntaje["auto_est"]  + puntaje["tele_est"]  + puntaje["endgame_score_est"]
    puntaje["score_min_total"] = puntaje["auto_min"]  + puntaje["tele_min"]  + puntaje["endgame_score_min"]
    puntaje["score_max_total"] = puntaje["auto_max"]  + puntaje["tele_max"]  + puntaje["endgame_score_max"]

    # RANKING POINTS
    fuel_est = puntaje["auto_est"] + puntaje["tele_est"]
    fuel_min = puntaje["auto_min"] + puntaje["tele_min"]
    fuel_max = puntaje["auto_max"] + puntaje["tele_max"]

    puntaje["ENERGIZED RP"]    = rp.get("ENERGIZED RP", 0)    if (fuel_est >= 100 or fuel_min >= 100 or fuel_max >= 100)    else 0
    puntaje["SUPERCHARGED RP"] = rp.get("SUPERCHARGED RP", 0) if (fuel_est >= 360 or fuel_min >= 360 or fuel_max >= 360)    else 0
    puntaje["TRAVERSAL RP"]    = rp.get("TRAVERSAL RP", 0)    if (puntaje["endgame_score_est"] >= 50 or
                                                                     puntaje["endgame_score_min"] >= 50 or
                                                                     puntaje["endgame_score_max"] >= 50) else 0

    return puntaje, rob1, rob2, rob3


