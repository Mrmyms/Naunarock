######## Estimados por equipo por match - Rolling (leave-one-out) ########
# Para el match N, el estimado del robot se calcula usando SOLO los datos
# de scouting y scores de TBA de los matches anteriores (1..N-1).
# Esto refleja lo que el scouter sabría ANTES de que se juegue ese match.

def simular_robot_hasta_match(equipo, match_num_limite, datos, equipos, matches_df):
    """
    Simula el robot con datos disponibles ANTES del match match_num_limite.
    Solo usa scouting y TBA de matches con match_num < match_num_limite.

    Args:
        equipo: Team ID (int)
        match_num_limite: número de match actual (se excluye y todos los posteriores)
        datos: DataFrame completo de scouting
        equipos: DataFrame de equipos
        matches_df: DataFrame de matches con scores de TBA

    Returns:
        dict igual al de simular_robot, pero usando solo datos previos
    """
    robot = {
        "equipo":             int(equipo),
        "nombre":             "nombre",
        "jugados_previos":    0,
        "auto_prom":          0.0,
        "auto_desv":          0.0,
        "auto_var":           0.0,
        "tele_prom":          0.0,
        "tele_desv":          0.0,
        "tele_var":           0.0,
        "endgame_nvl3_prob":  0,
        "endgame_nvl2_prob":  0,
        "endgame_nvl1_prob":  0,
        "endgame_none_prob":  0,
        "tipo_endgame":       "NONE",
        "endgame_score_est":  0,
        "endgame_score_min":  0,
        "endgame_score_max":  0,
        "auto_est":           0.0,
        "auto_min":           0.0,
        "auto_max":           0.0,
        "tele_est":           0.0,
        "tele_min":           0.0,
        "tele_max":           0.0,
        "score_est":          0.0,
        "score_min":          0.0,
        "score_max":          0.0,
        "EPA":                0
    }

    try:
        nombre_vals = equipos.loc[equipos["Team ID"] == equipo, "Names"].values
        robot["nombre"] = nombre_vals[0] if len(nombre_vals) > 0 else "Sin nombre"

        # Filtrar scouting SOLO de matches anteriores al límite
        data_equipo = datos.loc[datos["EQUIPO"] == equipo].copy().reset_index(drop=True).fillna(0)
        data_previa = data_equipo[data_equipo["MATCH"].astype(int) < match_num_limite].reset_index(drop=True)

        if len(data_previa) == 0:
            # Sin datos previos: no hay estimado posible
            return robot

        robot["jugados_previos"] = len(data_previa)

        # --- Scores de TBA de matches PREVIOS ---
        auto_scores_tba = []
        tele_scores_tba = []

        for i in range(len(data_previa)):
            mn = str(int(data_previa["MATCH"].iloc[i]))
            auto_s, tele_s, endgame_s = get_tba_score_for_team(equipo, mn, matches_df)
            if auto_s == 0 and tele_s == 0 and endgame_s == 0:
                continue
            auto_scores_tba.append(auto_s)
            tele_scores_tba.append(tele_s)

        # --- AUTO ---
        if auto_scores_tba:
            arr_auto = np.array(auto_scores_tba)
            robot["auto_prom"] = round(float(np.mean(arr_auto)), 2)
            robot["auto_desv"] = round(float(np.std(arr_auto)), 2)
            robot["auto_var"]  = round(float(np.var(arr_auto)), 2)

        # --- TELE (con filtro IQR) ---
        if tele_scores_tba:
            arr_tele = np.array(tele_scores_tba)
            q25 = np.quantile(arr_tele, 0.25)
            q75 = np.quantile(arr_tele, 0.75)
            filtrado = arr_tele[(arr_tele >= q25) & (arr_tele <= q75)]
            base = filtrado if filtrado.size > 0 else arr_tele
            robot["tele_prom"] = round(float(np.mean(base)), 2)
            robot["tele_desv"] = round(float(np.std(base)), 2)
            robot["tele_var"]  = round(float(np.var(base)), 2)

        # --- ENDGAME cualitativo (datos previos de scouting) ---
        if "ENDGAME" in data_previa.columns and not data_previa["ENDGAME"].empty:
            jerar_endgame = list(data_jerar(data_previa["ENDGAME"]))
            if jerar_endgame:
                n = len(jerar_endgame)
                robot["endgame_nvl3_prob"] = round(jerar_endgame.count("NVL3") / n * 100)
                robot["endgame_nvl2_prob"] = round(jerar_endgame.count("NVL2") / n * 100)
                robot["endgame_nvl1_prob"] = round(jerar_endgame.count("NVL1") / n * 100)
                robot["endgame_none_prob"] = round(jerar_endgame.count("NONE") / n * 100)

                robot["tipo_endgame"]      = safe_mode(jerar_endgame, "NONE")
                robot["endgame_score_est"] = scores.get(robot["tipo_endgame"], 0)

                # Mínimo: baja al peor nivel con prob ≥ 1%
                robot["endgame_score_min"] = scores.get("NVL3", 0)
                if robot["endgame_nvl1_prob"] >= 1:
                    robot["endgame_score_min"] = scores.get("NVL1", 0)
                if robot["endgame_none_prob"] >= 1:
                    robot["endgame_score_min"] = scores.get("NONE", 0)

                # Máximo: sube al mejor nivel con prob ≥ 1%
                robot["endgame_score_max"] = scores.get("NONE", 0)
                if robot["endgame_nvl1_prob"] >= 1:
                    robot["endgame_score_max"] = scores.get("NVL1", 0)
                if robot["endgame_nvl2_prob"] >= 1:
                    robot["endgame_score_max"] = scores.get("NVL2", 0)
                if robot["endgame_nvl3_prob"] >= 1:
                    robot["endgame_score_max"] = scores.get("NVL3", 0)

        # --- Estimados finales ---
        robot["auto_est"] = robot["auto_prom"]
        robot["auto_min"] = max(0.0, robot["auto_prom"] - robot["auto_desv"])
        robot["auto_max"] = robot["auto_prom"] + robot["auto_desv"]

        robot["tele_est"] = robot["tele_prom"]
        robot["tele_min"] = max(0.0, robot["tele_prom"] - robot["tele_desv"])
        robot["tele_max"] = robot["tele_prom"] + robot["tele_desv"]

        robot["score_est"] = robot["auto_est"] + robot["tele_est"] + robot["endgame_score_est"]
        robot["score_min"] = robot["auto_min"] + robot["tele_min"] + robot["endgame_score_min"]
        robot["score_max"] = robot["auto_max"] + robot["tele_max"] + robot["endgame_score_max"]

        robot["EPA"] = max(0, int(
            0.35 * robot["auto_est"] +
            0.45 * robot["tele_est"] +
            0.40 * robot["endgame_score_est"]
        ))

    except Exception as e:
        print(f"Error en robot {equipo} antes de match {match_num_limite}: {e}")

    return robot


def estimar_puntos_por_equipo_en_match(match_row, datos, teams_df, matches_df):
    """
    Para cada equipo en el match, calcula su estimado usando SOLO datos previos al match.
    Retorna lista de dicts por equipo.
    """
    match_code = match_row["match_code"]
    match_num  = int(match_row["match_num"])

    team_ids = [
        int(match_row["ROJO1"]), int(match_row["ROJO2"]), int(match_row["ROJO3"]),
        int(match_row["AZUL1"]), int(match_row["AZUL2"]), int(match_row["AZUL3"])
    ]

    equipo_scores = []
    for team_id in team_ids:
        sim = simular_robot_hasta_match(team_id, match_num, datos, teams_df, matches_df)
        equipo_scores.append({
            "match_code":              match_code,
            "match_num":               match_num,
            "team_id":                 team_id,
            "nombre":                  sim.get("nombre", ""),
            "jugados_previos":         sim.get("jugados_previos", 0),
            "estimated_auto_score":    round(sim.get("auto_est", 0), 2),
            "estimated_tele_score":    round(sim.get("tele_est", 0), 2),
            "estimated_endgame_score": sim.get("endgame_score_est", 0),
            "estimated_total_score":   round(sim.get("score_est", 0), 2),
            "score_min":               round(sim.get("score_min", 0), 2),
            "score_max":               round(sim.get("score_max", 0), 2),
            "tipo_endgame":            sim.get("tipo_endgame", "NONE"),
            "EPA":                     sim.get("EPA", 0)
        })
    return equipo_scores


